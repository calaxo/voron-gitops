"""Calibration print generators (pure functions, no I/O)."""

from __future__ import annotations

import math
from dataclasses import dataclass


def _f(v: float, nd: int = 3) -> str:
    s = f"{v:.{nd}f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


@dataclass
class PrintParams:
    nozzle_temp: float = 215.0
    bed_temp: float = 60.0
    filament_diameter: float = 1.75
    line_width: float = 0.48
    layer_height: float = 0.2
    travel_speed: float = 150.0
    retract_mm: float = 0.5
    retract_speed: float = 35.0
    z_hop: float = 0.4
    start_gcode: str | None = None  # e.g. "PRINT_START BED=60 EXTRUDER=215"
    end_gcode: str | None = None

    def e_per_mm(self, flow: float = 1.0) -> float:
        area = math.pi * (self.filament_diameter / 2) ** 2
        return self.line_width * self.layer_height / area * flow


def _start(p: PrintParams, title: str) -> list[str]:
    out = [f"; {title}", "; generated by voron-mcp"]
    if p.start_gcode:
        out += p.start_gcode.splitlines()
    else:
        out += [f"M140 S{_f(p.bed_temp)}", f"M104 S{_f(p.nozzle_temp)}", "G28",
                f"M190 S{_f(p.bed_temp)}", f"M109 S{_f(p.nozzle_temp)}"]
    out += ["G90", "M83", "G92 E0"]
    return out


def _end(p: PrintParams) -> list[str]:
    if p.end_gcode:
        return p.end_gcode.splitlines()
    return [f"G1 E-{_f(p.retract_mm)} F{_f(p.retract_speed * 60)}", "G91", "G1 Z10 F600", "G90",
            "M104 S0", "M140 S0", "M107", "M400"]


class _Writer:
    def __init__(self, p: PrintParams):
        self.p = p
        self.lines: list[str] = []
        self.x = self.y = 0.0

    def travel(self, x: float, y: float, z: float) -> None:
        p = self.p
        self.lines += [f"G1 E-{_f(p.retract_mm)} F{_f(p.retract_speed * 60)}",
                       f"G1 Z{_f(z + p.z_hop)} F1200",
                       f"G1 X{_f(x)} Y{_f(y)} F{_f(p.travel_speed * 60)}",
                       f"G1 Z{_f(z)} F1200",
                       f"G1 E{_f(p.retract_mm)} F{_f(p.retract_speed * 60)}"]
        self.x, self.y = x, y

    def extrude(self, x: float, y: float, speed: float, flow: float = 1.0) -> None:
        d = math.hypot(x - self.x, y - self.y)
        e = d * self.p.e_per_mm(flow)
        self.lines.append(f"G1 X{_f(x)} Y{_f(y)} E{_f(e, 5)} F{_f(speed * 60)}")
        self.x, self.y = x, y


def pa_line_test(center_x: float, center_y: float, pa_start: float = 0.0, pa_end: float = 0.07,
                 pa_step: float = 0.005, slow_speed: float = 20.0, fast_speed: float = 120.0,
                 slow_len: float = 20.0, fast_len: float = 40.0, spacing: float = 5.0,
                 params: PrintParams | None = None) -> str:
    """Klipper-style PA line test: one line per PA value, each slow/fast/slow,
    with a marker tab every 0.01 PA (long tab every 0.05) on the left."""
    p = params or PrintParams()
    n = int(round((pa_end - pa_start) / pa_step)) + 1
    values = [round(pa_start + i * pa_step, 6) for i in range(n)]
    total_len = 2 * slow_len + fast_len
    x0 = center_x - total_len / 2
    y0 = center_y - (n - 1) * spacing / 2
    z = p.layer_height
    w = _Writer(p)
    w.lines += _start(p, f"Pressure advance line test {pa_start}..{pa_end} step {pa_step}")
    w.lines += [";LAYER_CHANGE", f"G1 Z{_f(z + 5)} F1200"]
    # prime line
    w.travel(x0 - 10, y0 - 5, z)
    w.extrude(x0 - 10, y0 + (n - 1) * spacing + 5, slow_speed, 1.2)
    for i, pa in enumerate(values):
        y = y0 + i * spacing
        w.lines += [f"; PA={_f(pa, 4)}", f"SET_PRESSURE_ADVANCE ADVANCE={_f(pa, 4)}"]
        w.travel(x0, y, z)
        w.extrude(x0 + slow_len, y, slow_speed)
        w.extrude(x0 + slow_len + fast_len, y, fast_speed)
        w.extrude(x0 + total_len, y, slow_speed)
        cents = round(pa * 1000)
        if cents % 10 == 0:  # every 0.01: marker tab on the left
            tab = 6.0 if cents % 50 == 0 else 3.0
            w.travel(x0 - 2, y, z)
            w.extrude(x0 - 2 - tab, y, slow_speed)
    w.lines += ["SET_PRESSURE_ADVANCE ADVANCE=0  ; restore manually to your value"]
    w.lines += _end(p)
    return "\n".join(w.lines) + "\n"


def flow_squares_test(center_x: float, center_y: float, flows: list[float] | None = None,
                      size: float = 20.0, gap: float = 5.0, layers: int = 3, speed: float = 60.0,
                      params: PrintParams | None = None) -> str:
    """Row of solid squares (perimeter + zigzag fill), one extrusion multiplier
    per square (M221), `layers` layers each. Compare top surfaces."""
    p = params or PrintParams()
    flows = flows or [0.90, 0.95, 1.00, 1.05, 1.10]
    n = len(flows)
    total = n * size + (n - 1) * gap
    xs = [center_x - total / 2 + i * (size + gap) for i in range(n)]
    y0 = center_y - size / 2
    w = _Writer(p)
    w.lines += _start(p, f"Flow squares {flows}")
    lw = p.line_width
    for layer in range(layers):
        z = p.layer_height * (layer + 1)
        w.lines += [";LAYER_CHANGE", f";Z:{_f(z)}"]
        for x0, flow in zip(xs, flows):
            w.lines += [f"; square flow={flow}", f"M221 S{_f(flow * 100, 1)}"]
            # perimeter
            w.travel(x0, y0, z)
            for cx, cy in ((x0 + size, y0), (x0 + size, y0 + size), (x0, y0 + size), (x0, y0)):
                w.extrude(cx, cy, speed / 2)
            # zigzag fill, alternate direction each layer
            inner0, inner1 = lw, size - lw
            rows = max(1, int((inner1 - inner0) / lw))
            for r in range(rows + 1):
                off = inner0 + r * (inner1 - inner0) / rows
                if layer % 2 == 0:
                    a, b = (x0 + inner0, y0 + off), (x0 + inner1, y0 + off)
                else:
                    a, b = (x0 + off, y0 + inner0), (x0 + off, y0 + inner1)
                if r % 2:
                    a, b = b, a
                if r == 0:
                    w.travel(*a, z)
                else:
                    w.extrude(*a, speed)
                w.extrude(*b, speed)
    w.lines += ["M221 S100"]
    w.lines += _end(p)
    return "\n".join(w.lines) + "\n"
